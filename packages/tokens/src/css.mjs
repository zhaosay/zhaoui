import { base, modes, audiences, densities, trends, layout, brands, styles } from './tokens.mjs';
import { alpha } from './color.mjs';
import { brandCss, ALPHAS } from './brand.mjs';

const P = '--zh-';
const val = (v) => (typeof v === 'string' && v.startsWith('@') ? `var(${P}${v.slice(1)})` : v);
const decl = (o) => Object.entries(o).map(([k, v]) => `  ${P}${k}: ${val(v)};`).join('\n');

const STATUS = ['success', 'warning', 'danger', 'info'];
// Literal copies of everything a style pack may remap, so a flat region can be nested inside a soft page.
const FLAT_COLOUR = ['bg', 'bg-subtle', 'bg-elevated', 'bg-glass', 'border', 'border-strong'];
const FLAT_SHAPE = ['radius-sm', 'radius-md', 'radius-lg', 'shadow-sm', 'shadow-md', 'shadow-lg'];
const TINTS = { bg: 0.14, 'bg-subtle': 0.1, border: 0.35 };

/** Static tinted backgrounds for status colours (no runtime colour-mix needed). */
export function statusTints(mode) {
  const o = {};
  for (const s of STATUS) for (const [suffix, a] of Object.entries(TINTS)) o[`${s}-${suffix}`] = alpha(modes[mode][s], a);
  return o;
}

/** Maps the mode-independent brand variables onto the mode-specific semantic ones. */
export function brandMapping(mode) {
  const k = mode === 'light' ? 'l' : 'd';
  const o = {
    'color-primary': `@brand-${k}-primary`, 'color-primary-hover': `@brand-${k}-hover`,
    'color-primary-active': `@brand-${k}-active`, 'color-primary-subtle': `@brand-${k}-subtle`,
    'color-primary-text': `@brand-${k}-text`, 'on-primary': `@brand-${k}-on`,
    'meter-track': mode === 'light' ? '@brand-2' : '@brand-9',
    'selection-bg': `@brand-${k}-${mode === 'light' ? 'a22' : 'a35'}`,
  };
  for (const a of Object.keys(ALPHAS)) o[`primary-${a}`] = `@brand-${k}-${a}`;
  for (const n of ['base', 'o1', 'o2', 'o3']) o[`glass-${n}`] = `@brand-${k}-glass-${n}`;
  o['glass-shadow'] = `@brand-${k}-a20`;
  for (let i = 0; i < 8; i++) o[`seq-${i}`] = mode === 'light' ? `@brand-${i + 1}` : `@brand-${10 - i}`;
  return o;
}

function modeBlock(mode) {
  const sel = mode === 'light' ? ':root,\n[data-mode="light"]' : '[data-mode="dark"]';
  const body = { ...modes[mode], ...statusTints(mode), ...brandMapping(mode) };
  for (const k of FLAT_COLOUR) body[`flat-${k}`] = modes[mode][k];
  return `${sel} {\n  color-scheme: ${mode};\n${decl(body)}\n}\n`;
}

function layoutCss() {
  const [phone, tablet, desktop, large] = layout.tiers;
  const set = (t, extra = '') => `--zh-cols: ${t.cols}; --zh-gutter: ${t.gutter}; --zh-inner-pad: ${t.pad};${extra}`;
  return [
    `:root {\n  ${set(desktop)}\n  --zh-container-max: none;\n  --zh-touch-min: 0px;\n}`,
    `@media (max-width: ${tablet.max}px) {\n  :root { ${set(tablet)} }\n}`,
    `@media (max-width: ${phone.max}px) {\n  :root { ${set(phone)} }\n}`,
    `@media (min-width: ${large.min}px) {\n  :root { --zh-inner-pad: ${large.pad}; --zh-container-max: ${large.containerMax}; }\n}`,
    `@media (pointer: coarse) {\n  :root { --zh-touch-min: ${layout.touchMin}; }\n}`,
    `[data-screen="phone"],\n[data-screen="tablet"] {\n  --zh-touch-min: ${layout.touchMin};\n}`,
    `[data-screen="wall"] {\n  --zh-scale: ${layout.wall.scale};\n  --zh-gutter: ${layout.wall.gutter};\n  --zh-inner-pad: ${layout.wall.pad};\n  --zh-container-max: none;\n  --zh-touch-min: ${layout.wall.touchMin};\n}`,
  ].join('\n\n') + '\n';
}

export function buildCss() {
  const parts = ['/* @zhaoui/tokens — generated by scripts/build.mjs. Do not edit by hand. */\n'];
  parts.push(`:root {\n${decl(base)}\n}\n`);
  parts.push(layoutCss());
  for (const [name, o] of Object.entries(audiences)) {
    const withFlat = { ...o };
    for (const k of FLAT_SHAPE) withFlat[`flat-${k}`] = o[k];
    parts.push(`${name === 'b' ? ':root,\n[data-audience="b"]' : `[data-audience="${name}"]`} {\n${decl(withFlat)}\n}\n`);
  }
  for (const [name, o] of Object.entries(densities)) {
    parts.push(`${name === 'standard' ? ':root,\n[data-density="standard"]' : `[data-density="${name}"]`} {\n${decl(o)}\n}\n`);
  }
  parts.push(`:root,\n[data-audience],\n[data-density],\n[data-screen] {\n  --zh-control-h: max(var(--zh-touch-min, 0px), calc((var(--zh-control-h-base) + var(--zh-density)) * var(--zh-scale)));\n  --zh-fs: calc(var(--zh-font-base) * var(--zh-scale));\n}\n`);
  parts.push(modeBlock('light'), modeBlock('dark'));
  const flatReset = Object.fromEntries([...FLAT_COLOUR, ...FLAT_SHAPE].map((k) => [k, `@flat-${k}`]));
  parts.push(`[data-style="flat"] {\n${decl(flatReset)}\n}\n`);
  for (const [name, o] of Object.entries(styles)) if (Object.keys(o).length) parts.push(`[data-style="${name}"] {\n${decl(o)}\n}\n`);
  for (const [name, o] of Object.entries(trends)) {
    parts.push(`${name === 'cn' ? ':root,\n[data-trend="cn"]' : `[data-trend="${name}"]`} {\n${decl(o)}\n}\n`);
  }
  for (const [name, hex] of Object.entries(brands)) parts.push(brandCss(name, hex));
  return parts.join('\n');
}
