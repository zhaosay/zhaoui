const dist = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist');
mkdirSync(dist, { recursive: true });

const css = buildCss();
writeFileSync(join(dist, 'zhaoui.css'), css);

const resolveAliases = (o) => {
  const out = {};
  const get = (k, seen = []) => {
    const v = o[k];
    if (typeof v === 'string' && v.startsWith('@')) {
      if (seen.includes(k)) throw new Error(`alias cycle at ${k}`);
      return get(v.slice(1), [...seen, k]);
    }
    return v;
  };
  for (const k of Object.keys(o)) out[k] = get(k);
  return out;
};

// A soft region nested in a flat one (or the reverse) must not leak: every rule only applies when no
// [data-style="flat"] ancestor sits between the element and the page.
const scopeStyle = (cssText, name, other) => cssText.replace(new RegExp(`^(\\[data-style="${name}"\\][^{}]*?)\\s*\\{`, 'gm'), (m, sel) =>
  sel.split(',').map((one) => { const t = one.trim(); const guard = `:not([data-style="${other}"] *)`; const i = t.indexOf('::'); return i < 0 ? t + guard : t.slice(0, i) + guard + t.slice(i); }).join(',\n') + ' {');
writeFileSync(join(dist, 'zhaoui-style-glass.css'), scopeStyle(readFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', 'styles', 'glass.css'), 'utf8'), 'glass', 'flat'));

const json = {
  version: '0.1.0',
  base,
  modes: Object.fromEntries(Object.keys(modes).map((m) => [m, { ...resolveAliases(modes[m]), ...statusTints(m) }])),
  audiences,
  densities,
  trends,
  styles,
  layout,
  brands: Object.fromEntries(Object.entries(brands).map(([n, hex]) => [n, generateBrand(hex)])),
  brandMapping: { light: brandMapping('light'), dark: brandMapping('dark') },
};
writeFileSync(join(dist, 'tokens.figma.json'), JSON.stringify(figmaTokens(), null, 2) + '\n');
writeFileSync(join(dist, 'tokens.json'), JSON.stringify(json, null, 2) + '\n');
// Browser runtime: the same brand engine as the build, as a classic script (works from file://, no bundler).
